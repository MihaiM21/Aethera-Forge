using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using Aethera.Domain.Transport;

namespace Aethera.Engine.Proxy;

/// <summary>
/// Names of routers, services and middlewares (the Docker provider shares one namespace per Traefik, across every container on the server).
/// </summary>
public static partial class RouteNames
{
    /// <summary>Longest base name; leaves room for a group suffix (<c>-12</c>) and Traefik's <c>-https</c> within 63 characters.</summary>
    public const int MaxBaseLength = 54;

    /// <summary>
    /// The router/service name of a workload: <c>&lt;slug&gt;-&lt;first 8 hex digits of the workload id&gt;</c>. A slug is only unique per environment,
    /// so two <c>website</c> workloads in prod and dev (or any workload slugged <c>aethera</c>) must not share a name. The slug is shortened for a
    /// long name. The same workload always gets the same name, so consecutive deployments merge in the proxy (low-downtime strategy).
    /// </summary>
    public static string ForWorkload(string slug, Guid workloadId)
    {
        var suffix = "-" + workloadId.ToString("N")[..8];
        var clean = new string(slug.ToLowerInvariant().Select(c => c is >= 'a' and <= 'z' or >= '0' and <= '9' or '-' ? c : '-').ToArray()).Trim('-');
        if (clean.Length == 0) clean = "w";
        var max = MaxBaseLength - suffix.Length;
        if (clean.Length > max) clean = clean[..max].TrimEnd('-');
        return clean + suffix;
    }

    /// <summary>Name of the <paramref name="index"/>-th route group of a workload (zero-based): the base name, then <c>-2</c>, <c>-3</c>, ...</summary>
    public static string Group(string baseName, int index) => index == 0 ? baseName : $"{baseName}-{index + 1}";

    /// <summary>Labels of the control plane's own container (<c>deploy/docker-compose.prod.yml</c>): no workload may use these names.</summary>
    public static bool IsReserved(string name) => name is "aethera" or "aethera-http" or "aethera-https" or "aethera-redirect";
}

/// <summary>Traefik v3 with the Docker provider, Let's Encrypt HTTP-01 and (optionally) DNS-01 through Cloudflare (spec section 12, ADR 0010).</summary>
public sealed partial class TraefikProxyProvider : IProxyProvider
{
    /// <summary>HTTP-01 resolver.</summary>
    public const string CertResolver = "letsencrypt";

    /// <summary>DNS-01 resolver (Cloudflare), present when the server has domains with a DNS provider.</summary>
    public const string CloudflareResolver = "cloudflare";

    /// <summary>The proxy container's environment variable that carries the Cloudflare API token.</summary>
    public const string CloudflareTokenVariable = "CF_DNS_API_TOKEN";

    public string Name => "traefik";

    [GeneratedRegex(@"^(\*\.)?([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{1,62}$|^localhost$")]
    private static partial Regex HostRegex();

    [GeneratedRegex(@"^[a-z0-9][a-z0-9_-]{0,62}$")]
    private static partial Regex NameRegex();

    [GeneratedRegex(@"^/[A-Za-z0-9._~/-]*$")]
    private static partial Regex PathRegex();

    // A bcrypt htpasswd line, nothing else: a user name without separators, quotes or spaces and a 60 character modular-crypt hash.
    [GeneratedRegex(@"^[A-Za-z0-9._@-]{1,64}:\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$")]
    private static partial Regex HtpasswdRegex();

    [GeneratedRegex(@"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$")]
    private static partial Regex ResolverRegex();

    public static bool IsValidHost(string host) => HostRegex().IsMatch(host);

    public static bool IsValidHtpasswdLine(string line) => HtpasswdRegex().IsMatch(line);

    public ProxyEnsureCommand BuildEnsureCommand(ProxySettings settings)
    {
        var yaml = new StringBuilder();
        yaml.AppendLine("# Generated by Aethera. Edit through the API; manual changes are overwritten.");
        List<EnvVarSpec>? env = null;
        var dns = settings.DnsChallenge is { Provider: CloudflareResolver, ApiToken.Length: > 0 } c && settings.AcmeEmail is { Length: > 0 } ? c : null;
        if (dns is not null)
        {
            // The agent restarts the proxy when its configuration hash changes, not when its environment does. A fingerprint of the token (not
            // reversible: the token is long and random) makes a rotated token change the configuration, so the proxy picks the new one up.
            var fingerprint = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(dns.ApiToken)))[..12].ToLowerInvariant();
            yaml.AppendLine($"# dns-01 credential fingerprint: {fingerprint}");
            env = [EnvVarSpec.OfSecret(CloudflareTokenVariable, dns.ApiToken)];
        }

        yaml.AppendLine("entryPoints:");
        yaml.AppendLine("  web:");
        yaml.AppendLine("    address: \":80\"");
        yaml.AppendLine("  websecure:");
        yaml.AppendLine("    address: \":443\"");
        yaml.AppendLine("providers:");
        yaml.AppendLine("  docker:");
        yaml.AppendLine("    exposedByDefault: false");
        yaml.AppendLine($"    network: {settings.Network}");
        yaml.AppendLine("    watch: true");
        if (settings.AcmeEmail is { Length: > 0 } email)
        {
            if (email.Any(ch => char.IsWhiteSpace(ch) || ch is '"' or '\'' or '\\' or ':'))
                throw new ArgumentException("The ACME email contains characters that are not allowed.", nameof(settings));
            yaml.AppendLine("certificatesResolvers:");
            yaml.AppendLine($"  {CertResolver}:");
            yaml.AppendLine("    acme:");
            yaml.AppendLine($"      email: \"{email}\"");
            yaml.AppendLine("      storage: /acme/acme.json");
            if (settings.AcmeStaging)
                yaml.AppendLine("      caServer: https://acme-staging-v02.api.letsencrypt.org/directory");
            yaml.AppendLine("      httpChallenge:");
            yaml.AppendLine("        entryPoint: web");
            if (dns is not null)
            {
                yaml.AppendLine($"  {CloudflareResolver}:");
                yaml.AppendLine("    acme:");
                yaml.AppendLine($"      email: \"{email}\"");
                yaml.AppendLine("      storage: /acme/acme-cloudflare.json");
                if (settings.AcmeStaging)
                    yaml.AppendLine("      caServer: https://acme-staging-v02.api.letsencrypt.org/directory");
                yaml.AppendLine("      dnsChallenge:");
                yaml.AppendLine($"        provider: {dns.Provider}");
            }
        }
        yaml.AppendLine("api:");
        yaml.AppendLine("  dashboard: false");
        yaml.AppendLine("log:");
        yaml.AppendLine("  level: INFO");
        yaml.AppendLine("accessLog: {}");

        return new ProxyEnsureCommand("traefik", Encoding.UTF8.GetBytes(yaml.ToString()), Version: settings.Version, Env: env, Network: settings.Network);
    }

    public IReadOnlyDictionary<string, string> RouteLabels(RouteSpec route)
    {
        if (route.Hosts.Count == 0) return new Dictionary<string, string>();
        if (!NameRegex().IsMatch(route.Name) || RouteNames.IsReserved(route.Name)) throw new ArgumentException($"Invalid route name '{route.Name}'.", nameof(route));
        var redirect = route.RedirectTo is not null;
        if (!redirect && route.ContainerPort is < 1 or > 65535) throw new ArgumentException("Invalid container port.", nameof(route));
        foreach (var h in route.Hosts)
            if (!HostRegex().IsMatch(h)) throw new ArgumentException($"Invalid host name '{h}'.", nameof(route));
        if (route.PathPrefix is { } p && !PathRegex().IsMatch(p)) throw new ArgumentException("Invalid path prefix.", nameof(route));
        if (route.RedirectTo is { } target && (HostRegex().IsMatch(target) is false || target.StartsWith("*.", StringComparison.Ordinal)))
            throw new ArgumentException($"Invalid redirect target '{target}'.", nameof(route));
        if (route.CertResolver is { } resolver && !ResolverRegex().IsMatch(resolver)) throw new ArgumentException("Invalid certificate resolver.", nameof(route));
        if (route.BasicAuthUsers is { Count: > 0 } users && users.Any(u => !HtpasswdRegex().IsMatch(u)))
            throw new ArgumentException("Basic auth users must be bcrypt htpasswd lines.", nameof(route));

        var wildcard = route.Hosts.Any(h => h.StartsWith("*.", StringComparison.Ordinal));
        if (wildcard && route.CertResolver is not (CloudflareResolver or null))
            throw new ArgumentException("A wildcard host needs the DNS-01 certificate resolver.", nameof(route));

        var rule = string.Join(" || ", route.Hosts.Select(HostMatcher));
        if (route.PathPrefix is { Length: > 1 } prefix) rule = $"({rule}) && PathPrefix(`{prefix}`)";

        var n = route.Name;
        var labels = new Dictionary<string, string> { ["traefik.enable"] = "true", ["traefik.docker.network"] = route.Network };

        string service;
        var chain = new List<string>();
        if (redirect)
        {
            service = "noop@internal";
            labels[$"traefik.http.middlewares.{n}-redir.redirectregex.regex"] = "^https?://[^/]+(.*)$";
            labels[$"traefik.http.middlewares.{n}-redir.redirectregex.replacement"] = $"{(route.Https ? "https" : "http")}://{route.RedirectTo}${{1}}";
            labels[$"traefik.http.middlewares.{n}-redir.redirectregex.permanent"] = "true";
            chain.Add($"{n}-redir");
        }
        else
        {
            service = n;
            labels[$"traefik.http.services.{n}.loadbalancer.server.port"] = route.ContainerPort.ToString();
            if (route.BasicAuthUsers is { Count: > 0 } auth)
            {
                labels[$"traefik.http.middlewares.{n}-auth.basicauth.users"] = string.Join(",", auth);
                labels[$"traefik.http.middlewares.{n}-auth.basicauth.removeheader"] = "true";
                chain.Add($"{n}-auth");
            }
            if (route.StripPathPrefix && route.PathPrefix is { Length: > 1 } strip)
            {
                labels[$"traefik.http.middlewares.{n}-strip.stripprefix.prefixes"] = strip;
                chain.Add($"{n}-strip");
            }
        }

        if (!route.Https)
        {
            labels[$"traefik.http.routers.{n}.rule"] = rule;
            labels[$"traefik.http.routers.{n}.entrypoints"] = "web";
            labels[$"traefik.http.routers.{n}.service"] = service;
            if (chain.Count > 0) labels[$"traefik.http.routers.{n}.middlewares"] = string.Join(",", chain);
            return labels;
        }

        labels[$"traefik.http.routers.{n}-http.rule"] = rule;
        labels[$"traefik.http.routers.{n}-http.entrypoints"] = "web";
        labels[$"traefik.http.routers.{n}-http.service"] = service;
        if (redirect)
        {
            // The redirect target is the one hop: no detour through the https redirect first.
            labels[$"traefik.http.routers.{n}-http.middlewares"] = $"{n}-redir";
        }
        else if (route.RedirectToHttps)
        {
            labels[$"traefik.http.middlewares.{n}-redirect.redirectscheme.scheme"] = "https";
            labels[$"traefik.http.middlewares.{n}-redirect.redirectscheme.permanent"] = "true";
            labels[$"traefik.http.routers.{n}-http.middlewares"] = $"{n}-redirect";
        }
        else if (chain.Count > 0)
        {
            labels[$"traefik.http.routers.{n}-http.middlewares"] = string.Join(",", chain);
        }

        labels[$"traefik.http.routers.{n}-https.rule"] = rule;
        labels[$"traefik.http.routers.{n}-https.entrypoints"] = "websecure";
        labels[$"traefik.http.routers.{n}-https.service"] = service;
        labels[$"traefik.http.routers.{n}-https.tls"] = "true";
        if (route.CertResolver is { } certResolver) labels[$"traefik.http.routers.{n}-https.tls.certresolver"] = certResolver;
        if (chain.Count > 0) labels[$"traefik.http.routers.{n}-https.middlewares"] = string.Join(",", chain);
        if (wildcard)
        {
            // A regular expression names no domain, so the certificate's names are listed (every host of the router, not only the wildcard).
            for (var i = 0; i < route.Hosts.Count; i++) labels[$"traefik.http.routers.{n}-https.tls.domains[{i}].main"] = route.Hosts[i];
        }
        return labels;
    }

    /// <summary>
    /// <c>Host(`a.example.com`)</c>, or for <c>*.example.com</c> a Traefik v3 <c>HostRegexp</c> over exactly one label. The host passed the strict
    /// grammar (letters, digits, hyphens, dots), so nothing in the generated rule can come from a user.
    /// </summary>
    private static string HostMatcher(string host) =>
        host.StartsWith("*.", StringComparison.Ordinal)
            ? $"HostRegexp(`^[a-z0-9-]+\\.{host[2..].Replace(".", "\\.")}$`)"
            : $"Host(`{host}`)";
}
